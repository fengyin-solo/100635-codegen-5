// 严格度档位：数字越大越严。规则冲突时一律取更严的一档，宽松的一档降级成提示。
export const SEVERITY_RANK: Record<Severity, number> = { 严重: 3, 一般: 2, 轻微: 1 }
export const SEVERITY_ORDER: Severity[] = ['严重', '一般', '轻微']

// 结论严格度：不合格 > 有条件合格 > 合格。两个入口结论打架时只采纳更严的一档。
export const CONCLUSION_RANK = { 不合格: 3, 有条件合格: 2, 合格: 1 } as const

export function stricterSeverity(a?: Severity, b?: Severity): {
  effective: Severity
  basis: string
  hint?: string
} {
  if (a && b) {
    if (a === b) {
      return {
        effective: a,
        basis: `建设单位与接收单位均判定为「${a}」，两方一致，按一致档「${a}」登记。`,
      }
    }
    const winner = SEVERITY_RANK[a] > SEVERITY_RANK[b] ? a : b
    const winnerSide = SEVERITY_RANK[a] > SEVERITY_RANK[b] ? '建设单位' : '接收单位'
    const loser = winner === a ? b : a
    return {
      effective: winner,
      basis: `建设单位判「${a}」、接收单位判「${b}」，按"规则冲突取更严一档"，采纳${winnerSide}的「${winner}」。`,
      hint: `宽松一档「${loser}」降级为提示，不作为责任期判定依据。`,
    }
  }
  if (a || b) {
    const only = (a ?? b) as Severity
    const side = a ? '建设单位' : '接收单位'
    return { effective: only, basis: `仅${side}单方判定为「${only}」，按单方判定登记并保留待复核。` }
  }
  return { effective: '一般', basis: '两方均未给出书面判定，缺项列入待查台账，暂按「一般」挂起。' }
}

